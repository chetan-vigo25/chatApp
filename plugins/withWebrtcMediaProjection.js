/**
 * Expo config plugin: turn on react-native-webrtc's MediaProjection foreground
 * service so phone SCREEN SHARE actually sends frames.
 *
 * Android 10+ only lets an app capture the screen while a foreground service of
 * type `mediaProjection` is running. react-native-webrtc ships that service
 * (MediaProjectionService) but only starts it when
 * `WebRTCModuleOptions.enableMediaProjectionService` is true — and the default is
 * FALSE. With the flag off, getDisplayMedia() still resolves with a live track
 * (permission was granted), but ScreenCapturerAndroid.startCapture throws a
 * SecurityException that the library swallows: no frames ever reach the encoder
 * (outbound-rtp framesEncoded=0, 0x0) and the web shows "Waiting for the shared
 * screen…" forever.
 *
 * Must be a config plugin, not a hand-edit: `android/` is regenerated by
 * `expo prebuild --clean` / EAS, which would drop the line.
 *
 * Idempotent.
 */
const { withMainApplication } = require('@expo/config-plugins');

const IMPORT = 'import com.oney.WebRTCModule.WebRTCModuleOptions';
const FLAG = 'WebRTCModuleOptions.getInstance().enableMediaProjectionService = true';

const withWebrtcMediaProjection = (config) =>
  withMainApplication(config, (cfg) => {
    if (cfg.modResults.language !== 'kt') {
      throw new Error(
        '[withWebrtcMediaProjection] expected a Kotlin MainApplication; got ' +
          cfg.modResults.language,
      );
    }
    let contents = cfg.modResults.contents;
    if (contents.includes(FLAG)) return cfg;

    if (!contents.includes(IMPORT)) {
      contents = contents.replace(
        /(import android\.app\.Application\r?\n)/,
        `$1${IMPORT}\n`,
      );
    }
    contents = contents.replace(
      /(override fun onCreate\(\) \{\r?\n\s*super\.onCreate\(\)\r?\n)/,
      `$1    // Required for screen share: starts the mediaProjection foreground service.\n    ${FLAG}\n`,
    );
    if (!contents.includes(FLAG)) {
      throw new Error('[withWebrtcMediaProjection] could not find MainApplication.onCreate');
    }
    cfg.modResults.contents = contents;
    return cfg;
  });

module.exports = withWebrtcMediaProjection;
